import * as path from "node:path";
import { z } from "zod";
import { type ProviderModel, providerModelCapabilityIds } from "../src/sdk.ts";

export const PROVIDER_MODEL_CATALOG_SOURCE_PATH = path.join(
	import.meta.dir,
	"provider-model-catalog.source.json"
);

const nonEmptyIdentity = z
	.string()
	.min(1)
	.refine((value) => value.trim() === value);
const capabilitySchema = z.enum(providerModelCapabilityIds);

const modelOverrideSchema = z
	.object({
		capabilities: z
			.array(capabilitySchema)
			.min(1)
			.refine((values) => new Set(values).size === values.length)
			.optional(),
		modelId: nonEmptyIdentity,
		protocolId: nonEmptyIdentity.optional(),
	})
	.strict();

const providerModelSchema = z.union([nonEmptyIdentity, modelOverrideSchema]);
const providerSourceSchema = z
	.object({
		models: z.array(providerModelSchema).min(1),
		protocolId: nonEmptyIdentity,
		providerId: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/u),
	})
	.strict();
const providerModelCatalogSourceSchema = z
	.object({ providers: z.array(providerSourceSchema).min(1) })
	.strict();

type ProviderModelCatalogInput = z.infer<
	typeof providerModelCatalogSourceSchema
>;

export type ProviderModelCatalogSource = Readonly<{
	providers: readonly Readonly<{
		models: readonly ProviderModel[];
		providerId: string;
	}>[];
}>;

export type GeneratedProviderModelFile = Readonly<{
	contents: string;
	fileName: string;
	providerId: string;
}>;

/** Parses compact provider defaults and expands them into runtime Provider Models. */
export const parseProviderModelCatalogSource = (
	input: unknown
): ProviderModelCatalogSource => {
	const source: ProviderModelCatalogInput =
		providerModelCatalogSourceSchema.parse(input);
	const providerIds = new Set<string>();

	const providers = source.providers.map((provider) => {
		if (providerIds.has(provider.providerId)) {
			throw new Error(`Duplicate provider ID '${provider.providerId}'.`);
		}
		providerIds.add(provider.providerId);

		const modelIds = new Set<string>();
		const models = provider.models.map((sourceModel): ProviderModel => {
			const model =
				typeof sourceModel === "string"
					? { modelId: sourceModel }
					: sourceModel;
			if (modelIds.has(model.modelId)) {
				throw new Error(
					`Duplicate Provider Model '${provider.providerId}/${model.modelId}'.`
				);
			}
			modelIds.add(model.modelId);

			return {
				modelId: model.modelId,
				protocolId: model.protocolId ?? provider.protocolId,
				providerId: provider.providerId,
				...(model.capabilities === undefined
					? {}
					: { capabilities: model.capabilities }),
			};
		});
		return { models, providerId: provider.providerId };
	});
	return { providers };
};

/** Renders deterministic, provider-scoped TypeScript from enriched model records. */
export const generateProviderModelCatalog = (
	models: readonly ProviderModel[],
	provenance: Readonly<{ snapshotDate: string; source: string }>
): readonly GeneratedProviderModelFile[] => {
	const modelsByProvider = new Map<string, ProviderModel[]>();
	for (const model of models) {
		const providerModels = modelsByProvider.get(model.providerId);
		if (providerModels) {
			providerModels.push(model);
		} else {
			modelsByProvider.set(model.providerId, [model]);
		}
	}
	return [...modelsByProvider.entries()]
		.toSorted(([left], [right]) => {
			if (left < right) {
				return -1;
			}
			if (left > right) {
				return 1;
			}
			return 0;
		})
		.map(([providerId, providerModels]) => ({
			contents: [
				"// Generated by packages/ai/scripts/sync-provider-model-catalog.ts — do not edit.",
				`// Snapshot date: ${provenance.snapshotDate}. Source: ${provenance.source}.`,
				'import type { ProviderModel } from "../sdk.ts";',
				"",
				`export const providerModels = ${JSON.stringify(providerModels, null, "\t")} as const satisfies readonly ProviderModel[];`,
				"",
			].join("\n"),
			fileName: `${providerId}.generated.ts`,
			providerId,
		}));
};
